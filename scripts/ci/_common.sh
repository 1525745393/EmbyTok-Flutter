#!/usr/bin/env bash
# ============================================================
# CI 共享工具函数库
# 被 scripts/ci/precheck-*.sh 通过 source 引入，提供日志与工具检测能力
# 设计原则：工具缺失时降级（exit 0 + warning），不阻断整条流水线
# ============================================================

# 为什么启用严格模式：未定义变量、管道失败、命令失败都应尽早暴露，
# 避免静默错误在 CI 中产生"假通过"
set -euo pipefail

# ============================================================
# 颜色转义码
# 为什么无条件启用颜色：与 scripts/flutter-check.sh 风格保持一致，
# GitHub Actions 日志会自动渲染 ANSI 转义码
# ============================================================
BLUE='\033[0;34m'
GREEN='\033[0;32m'
RED='\033[0;31m'
YELLOW='\033[1;33m'
NC='\033[0m'

# ============================================================
# 日志函数：统一前缀，便于 CI 日志检索与归类
# 使用 printf 而非 echo -e：printf 行为跨平台更稳定
# ============================================================
log_info()    { printf "${BLUE}[INFO]${NC} %s\n" "$*"; }
log_success() { printf "${GREEN}✅ %s${NC}\n" "$*"; }
log_error()   { printf "${RED}❌ %s${NC}\n" "$*"; }
log_warn()    { printf "${YELLOW}⚠️  %s${NC}\n" "$*"; }

# ============================================================
# 检测工具是否安装
# 为什么缺失时 exit 0 而非 exit 1：CI 运行环境差异较大，
# 工具缺失不应阻断整条流水线。改为发出 GitHub Actions
# warning 注解并退出 0，由人工决定是否补救
# 调用方注意：require_tool 命中缺失会直接结束脚本，
# 后续逻辑不会执行；若需"缺失后继续执行其他检查"，
# 请改用内联 command -v 检测
# ============================================================
require_tool() {
    local tool="$1"
    if ! command -v "$tool" >/dev/null 2>&1; then
        echo "::warning::工具 '$tool' 未安装，跳过相关检查（降级模式）"
        exit 0
    fi
}
